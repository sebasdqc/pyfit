export type TranslationKey = keyof typeof translations

// Special keys that return string[] need separate handling
type ArrayKey = 'historial_months' | 'historial_days_abbr' | 'stats_months'
type ScalarKey = Exclude<TranslationKey, ArrayKey>

export function getTranslation(key: ScalarKey, lang: Lang): string {
  const entry = translations[key]
  return (entry as { es: string; en: string })[lang] ?? (entry as { es: string; en: string }).es
}

export function getTranslationArray(key: ArrayKey, lang: Lang): string[] {
  const entry = translations[key]
  return [...(entry as { es: readonly string[]; en: readonly string[] })[lang]]
}

export default translations
